-- Skema IntegrityView untuk Supabase.
-- Jalankan seluruh file ini di Supabase SQL Editor (Project > SQL Editor).

create table if not exists public.survey_responses (
  id bigint generated by default as identity primary key,
  nama_instrumen text not null,
  email_responden text,
  data_jawaban jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists idx_survey_responses_instrumen
  on public.survey_responses (nama_instrumen);

create index if not exists idx_survey_responses_created_at
  on public.survey_responses (created_at desc);

-- Aktifkan RLS: frontend (anon) hanya boleh membaca, penulisan lewat
-- Edge Function yang memakai service_role (service_role melewati RLS).
alter table public.survey_responses enable row level security;

grant usage on schema public to anon, authenticated, service_role;
revoke all on public.survey_responses from anon, authenticated;
grant select on public.survey_responses to anon, authenticated;
grant all on public.survey_responses to service_role;

drop policy if exists "baca publik survey_responses" on public.survey_responses;
create policy "baca publik survey_responses"
  on public.survey_responses
  for select
  to anon, authenticated
  using (true);

-- =====================================================================
-- Pengaduan & Whistleblowing
-- Dua tabel terpisah agar alur penanganan WBS bisa dibatasi terpisah.
-- Penulisan hanya lewat Edge Function kirim-laporan (service_role);
-- anon tidak diberi akses baca/tulis langsung (data berisi PII).
-- =====================================================================

create table if not exists public.pengaduan (
  id bigint generated by default as identity primary key,
  kode text not null unique,
  judul text not null check (char_length(judul) between 3 and 200),
  kategori text not null check (char_length(kategori) between 1 and 100),
  lokasi text not null default '' check (char_length(lokasi) <= 200),
  deskripsi text not null check (char_length(deskripsi) between 10 and 5000),
  anonim boolean not null default false,
  nama_pelapor text check (char_length(nama_pelapor) <= 200),
  kontak_pelapor text check (char_length(kontak_pelapor) <= 200),
  hubungan text check (char_length(hubungan) <= 100),
  status text not null default 'Baru'
    check (status in ('Baru', 'Diproses', 'Selesai')),
  pic text not null default '',
  riwayat jsonb not null default '[]'::jsonb,
  catatan_internal jsonb not null default '[]'::jsonb,
  balasan jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint pengaduan_anonim_tanpa_identitas check (
    not anonim
    or (nama_pelapor is null and kontak_pelapor is null and hubungan is null)
  )
);

create table if not exists public.whistleblowing (
  id bigint generated by default as identity primary key,
  kode text not null unique,
  judul text not null check (char_length(judul) between 3 and 200),
  kategori text not null check (char_length(kategori) between 1 and 100),
  lokasi text not null default '' check (char_length(lokasi) <= 200),
  deskripsi text not null check (char_length(deskripsi) between 10 and 5000),
  anonim boolean not null default false,
  nama_pelapor text check (char_length(nama_pelapor) <= 200),
  kontak_pelapor text check (char_length(kontak_pelapor) <= 200),
  hubungan text check (char_length(hubungan) <= 100),
  status text not null default 'Baru'
    check (status in ('Baru', 'Diproses', 'Selesai')),
  pic text not null default '',
  riwayat jsonb not null default '[]'::jsonb,
  catatan_internal jsonb not null default '[]'::jsonb,
  balasan jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint whistleblowing_anonim_tanpa_identitas check (
    not anonim
    or (nama_pelapor is null and kontak_pelapor is null and hubungan is null)
  )
);

create index if not exists idx_pengaduan_status
  on public.pengaduan (status);
create index if not exists idx_pengaduan_created_at
  on public.pengaduan (created_at desc);
create index if not exists idx_pengaduan_kategori
  on public.pengaduan (kategori);

create index if not exists idx_whistleblowing_status
  on public.whistleblowing (status);
create index if not exists idx_whistleblowing_created_at
  on public.whistleblowing (created_at desc);
create index if not exists idx_whistleblowing_kategori
  on public.whistleblowing (kategori);

-- Kode tiket: ADU-YYYY-0001 / WBS-YYYY-001. id identity sudah terisi
-- sebelum trigger BEFORE INSERT, jadi kode memakai id agar unik.
create or replace function public.isi_kode_laporan()
returns trigger
language plpgsql
as $$
declare
  prefix text;
  lebar integer;
begin
  if tg_table_name = 'whistleblowing' then
    prefix := 'WBS';
    lebar := 3;
  else
    prefix := 'ADU';
    lebar := 4;
  end if;

  if new.id is null then
    new.id := nextval(pg_get_serial_sequence('public.' || tg_table_name, 'id'));
  end if;

  if new.kode is null or btrim(new.kode) = '' then
    new.kode := prefix
      || '-' || to_char((coalesce(new.created_at, now()) at time zone 'Asia/Jakarta'), 'YYYY')
      || '-' || lpad(new.id::text, lebar, '0');
  end if;

  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists trg_kode_pengaduan on public.pengaduan;
create trigger trg_kode_pengaduan
  before insert or update on public.pengaduan
  for each row execute function public.isi_kode_laporan();

drop trigger if exists trg_kode_whistleblowing on public.whistleblowing;
create trigger trg_kode_whistleblowing
  before insert or update on public.whistleblowing
  for each row execute function public.isi_kode_laporan();

revoke all on function public.isi_kode_laporan() from public, anon, authenticated;
grant execute on function public.isi_kode_laporan() to service_role;

alter table public.pengaduan enable row level security;
alter table public.whistleblowing enable row level security;

revoke all on public.pengaduan from anon, authenticated;
revoke all on public.whistleblowing from anon, authenticated;

grant all on public.pengaduan to service_role;
grant all on public.whistleblowing to service_role;
grant usage, select on sequence public.pengaduan_id_seq to service_role;
grant usage, select on sequence public.whistleblowing_id_seq to service_role;

-- Mulai sequence di 1000/100 agar kode laporan baru tidak bertabrakan dengan
-- data demo PENGADUAN_SEED di frontend (ADU-2026-0001..0004, WBS-2026-001).
select setval(
  'public.pengaduan_id_seq',
  greatest(1000, coalesce((select max(id) from public.pengaduan), 0) + 1),
  false
)
where not exists (select 1 from public.pengaduan);

select setval(
  'public.whistleblowing_id_seq',
  greatest(100, coalesce((select max(id) from public.whistleblowing), 0) + 1),
  false
)
where not exists (select 1 from public.whistleblowing);
