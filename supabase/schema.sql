-- Skema IntegrityView untuk Supabase.
-- Jalankan seluruh file ini di Supabase SQL Editor (Project > SQL Editor).

create table if not exists public.survey_responses (
  id bigint generated by default as identity primary key,
  nama_instrumen text not null,
  email_responden text,
  data_jawaban jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists idx_survey_responses_instrumen
  on public.survey_responses (nama_instrumen);

create index if not exists idx_survey_responses_created_at
  on public.survey_responses (created_at desc);

-- Aktifkan RLS: frontend (anon) hanya boleh membaca, penulisan lewat
-- Edge Function yang memakai service_role (service_role melewati RLS).
alter table public.survey_responses enable row level security;

grant usage on schema public to anon, authenticated, service_role;
revoke all on public.survey_responses from anon, authenticated;
grant select on public.survey_responses to anon, authenticated;
grant all on public.survey_responses to service_role;

drop policy if exists "baca publik survey_responses" on public.survey_responses;
create policy "baca publik survey_responses"
  on public.survey_responses
  for select
  to anon, authenticated
  using (true);
