create table if not exists public.pengaduan (
  id bigint generated by default as identity primary key,
  kode text not null unique,
  judul text not null check (char_length(judul) between 3 and 200),
  kategori text not null check (char_length(kategori) between 1 and 100),
  lokasi text not null default '' check (char_length(lokasi) <= 200),
  deskripsi text not null check (char_length(deskripsi) between 10 and 5000),
  anonim boolean not null default false,
  nama_pelapor text check (char_length(nama_pelapor) <= 200),
  kontak_pelapor text check (char_length(kontak_pelapor) <= 200),
  hubungan text check (char_length(hubungan) <= 100),
  status text not null default 'Baru'
    check (status in ('Baru', 'Diproses', 'Selesai')),
  pic text not null default '',
  riwayat jsonb not null default '[]'::jsonb,
  catatan_internal jsonb not null default '[]'::jsonb,
  balasan jsonb not null default '[]'::jsonb,
  lampiran jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint pengaduan_anonim_tanpa_identitas check (
    not anonim
    or (nama_pelapor is null and kontak_pelapor is null and hubungan is null)
  )
);

create table if not exists public.whistleblowing (
  id bigint generated by default as identity primary key,
  kode text not null unique,
  judul text not null check (char_length(judul) between 3 and 200),
  kategori text not null check (char_length(kategori) between 1 and 100),
  lokasi text not null default '' check (char_length(lokasi) <= 200),
  deskripsi text not null check (char_length(deskripsi) between 10 and 5000),
  anonim boolean not null default false,
  nama_pelapor text check (char_length(nama_pelapor) <= 200),
  kontak_pelapor text check (char_length(kontak_pelapor) <= 200),
  hubungan text check (char_length(hubungan) <= 100),
  status text not null default 'Baru'
    check (status in ('Baru', 'Diproses', 'Selesai')),
  pic text not null default '',
  riwayat jsonb not null default '[]'::jsonb,
  catatan_internal jsonb not null default '[]'::jsonb,
  balasan jsonb not null default '[]'::jsonb,
  lampiran jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint whistleblowing_anonim_tanpa_identitas check (
    not anonim
    or (nama_pelapor is null and kontak_pelapor is null and hubungan is null)
  )
);

