create table if not exists public.survey_responses (
  id bigint generated by default as identity primary key,
  nama_instrumen text not null,
  -- HMAC-SHA256 dari email responden. Email asli tidak disimpan.
  responden_hash text,
  hash_version smallint not null default 1,
  data_jawaban jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists idx_survey_responses_instrumen
  on public.survey_responses (nama_instrumen);

create index if not exists idx_survey_responses_created_at
  on public.survey_responses (created_at desc);

create index if not exists idx_survey_responses_responden_hash
  on public.survey_responses (responden_hash, nama_instrumen, created_at desc);

-- Hapus kunci email dari payload sebelum data disimpan/dibaca frontend.
create or replace function public.sanitasi_data_jawaban(p_data jsonb)
returns jsonb
language sql
immutable
set search_path = public, pg_temp
as $$
  select case
    when jsonb_typeof(coalesce(p_data, '{}'::jsonb)) <> 'object' then '{}'::jsonb
    else coalesce((
      select jsonb_object_agg(entry.key, entry.value)
      from jsonb_each(coalesce(p_data, '{}'::jsonb)) as entry
      where lower(btrim(entry.key)) not in (
        'email', 'email address', 'alamat email', 'email responden',
        'surel', 'respondent email', '__respondent_email'
      )
        and lower(btrim(entry.key)) not like '%email%'
    ), '{}'::jsonb)
  end;
$$;

revoke all on function public.sanitasi_data_jawaban(jsonb)
  from public, anon, authenticated;
grant execute on function public.sanitasi_data_jawaban(jsonb) to service_role;

-- Aktifkan RLS. Anon tidak lagi membaca tabel mentah; frontend memakai RPC
-- di bawah yang sudah membuang email dari data_jawaban.
alter table public.survey_responses enable row level security;

grant usage on schema public to anon, authenticated, service_role;
revoke all on public.survey_responses from anon, authenticated;
grant all on public.survey_responses to service_role;

drop policy if exists "baca publik survey_responses" on public.survey_responses;

-- Jalur baca aman untuk dashboard: tanpa email_responden dan tanpa
-- "Email Address" di dalam data_jawaban.
create or replace function public.survey_rows_safe()
returns table (
  id bigint,
  nama_instrumen text,
  data_jawaban jsonb,
  created_at timestamptz,
  responden_hash text
)
language sql
security definer
stable
set search_path = public, pg_temp
as $$
  select
    r.id,
    r.nama_instrumen,
    public.sanitasi_data_jawaban(r.data_jawaban) as data_jawaban,
    r.created_at,
    r.responden_hash
  from public.survey_responses r
  order by r.created_at desc;
$$;

revoke all on function public.survey_rows_safe() from public;
grant execute on function public.survey_rows_safe() to anon, authenticated;

-- =====================================================================
-- Pengaduan & Whistleblowing
-- Dua tabel terpisah agar alur penanganan WBS bisa dibatasi terpisah.
-- Penulisan hanya lewat Edge Function kirim-laporan (service_role);
-- anon tidak diberi akses baca/tulis langsung (data berisi PII).
