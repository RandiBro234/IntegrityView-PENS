-- Kode tiket: ADU-YYYY-0001 / WBS-YYYY-001. id identity sudah terisi
-- sebelum trigger BEFORE INSERT, jadi kode memakai id agar unik.
create or replace function public.isi_kode_laporan()
returns trigger
language plpgsql
as $$
declare
  prefix text;
  lebar integer;
begin
  if tg_table_name = 'whistleblowing' then
    prefix := 'WBS';
    lebar := 3;
  else
    prefix := 'ADU';
    lebar := 4;
  end if;

  if new.id is null then
    new.id := nextval(pg_get_serial_sequence('public.' || tg_table_name, 'id'));
  end if;

  if new.kode is null or btrim(new.kode) = '' then
    new.kode := prefix
      || '-' || to_char((coalesce(new.created_at, now()) at time zone 'Asia/Jakarta'), 'YYYY')
      || '-' || lpad(new.id::text, lebar, '0');
  end if;

  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists trg_kode_pengaduan on public.pengaduan;
create trigger trg_kode_pengaduan
  before insert or update on public.pengaduan
  for each row execute function public.isi_kode_laporan();

drop trigger if exists trg_kode_whistleblowing on public.whistleblowing;
create trigger trg_kode_whistleblowing
  before insert or update on public.whistleblowing
  for each row execute function public.isi_kode_laporan();

revoke all on function public.isi_kode_laporan() from public, anon, authenticated;
grant execute on function public.isi_kode_laporan() to service_role;

alter table public.pengaduan enable row level security;
alter table public.whistleblowing enable row level security;

