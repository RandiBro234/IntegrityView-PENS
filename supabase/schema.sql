-- Mulai sequence di 1000/100 agar kode laporan baru tidak bertabrakan dengan
-- data demo PENGADUAN_SEED di frontend (ADU-2026-0001..0004, WBS-2026-001).
select setval(
  'public.pengaduan_id_seq',
  greatest(1000, coalesce((select max(id) from public.pengaduan), 0) + 1),
  false
)
where not exists (select 1 from public.pengaduan);

select setval(
  'public.whistleblowing_id_seq',
  greatest(100, coalesce((select max(id) from public.whistleblowing), 0) + 1),
  false
)
where not exists (select 1 from public.whistleblowing);


